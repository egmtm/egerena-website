/* Theme page: the app preview (Themes menu, All Themes, language switch) on the app's own markup and strings.
   The site theme, mode button and language menu are the shared site script's (/apps/egm-downloader.js).
   Data comes from app-data.js (generated by tools/theme-page/build.py). */
(function () {
  'use strict';
  var D = window.TP_DATA;
  if (!D) return;

  function sget(k) { try { return localStorage.getItem(k); } catch (e) { return null; } }
  function sset(k, v) { try { localStorage.setItem(k, v); } catch (e) {} }

  // ── Language: a choice saved on the site wins, then the browser's languages ──
  var CODES = D.langs.codes;
  function wantedLang() {
    var s = sget(D.site.langKey);
    if (s && CODES.indexOf(s) >= 0) return s;
    var list = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || 'en'];
    for (var i = 0; i < list.length; i++) {
      var c = String(list[i]).toLowerCase().split('-')[0];
      if (CODES.indexOf(c) >= 0) return c;
    }
    return 'en';
  }

  // The page keeps the previewed app theme under its own keys (the site theme uses egm-theme).
  var PKEY = 'egm-themes-page-theme', RKEY = 'egm-themes-page-recent', CKEY = 'egm-themes-page-collapsed';

  function init() {
    var $ = function (sel, el) { return (el || document).querySelector(sel); };
    var $$ = function (sel, el) { return Array.prototype.slice.call((el || document).querySelectorAll(sel)); };
    // Mount the preview in shadow roots, so the site's styles and the app's styles never meet
    function mount(hostId, tplId) {
      var host = $('#' + hostId), tpl = $('#' + tplId);
      if (!host || !tpl || !host.attachShadow) return null;
      var sr = host.attachShadow({ mode: 'open' });
      sr.appendChild(tpl.content.cloneNode(true));
      return sr;
    }
    var winRoot = mount('tp-win-host', 'tp-win-tpl'), atwRoot = mount('tp-atw-host', 'tp-atw-tpl');
    if (!winRoot || !atwRoot) return;
    var win = winRoot.querySelector('#tp-win'), atw = atwRoot.querySelector('#tp-atw'), atwHost = $('#tp-atw-host');
    function inPath(e, el) { return (e.composedPath ? e.composedPath() : [e.target]).indexOf(el) >= 0; }
    var frames = [win, atw];
    var TH = D.themes;

    // ── App strings (the app's i18nGet / i18nApply: textContent and a short list of attributes) ──
    var lang = 'en', STR = D.strings.en;
    function g(k) {
      var v = STR[k];
      if (typeof v === 'string') return v;
      v = D.strings.en[k];
      return typeof v === 'string' ? v : null;
    }
    function f(k) {
      var a = Array.prototype.slice.call(arguments, 1), v = g(k);
      return v === null ? '' : v.replace(/\{(\d+)\}/g, function (_, i) { return a[i] !== undefined ? String(a[i]) : ''; });
    }
    var SAFE = ['title', 'placeholder', 'aria-label', 'alt'];
    function applyStrings(scope) {
      $$('[data-i18n]', scope).forEach(function (el) { var v = g(el.getAttribute('data-i18n')); if (v !== null) el.textContent = v; });
      $$('[data-i18n-attr]', scope).forEach(function (el) {
        el.getAttribute('data-i18n-attr').split(',').forEach(function (pair) {
          var i = pair.indexOf(':');
          if (i < 1) return;
          var a = pair.slice(0, i).trim(), v = g(pair.slice(i + 1).trim());
          if (SAFE.indexOf(a) >= 0 && v !== null) el.setAttribute(a, v);
        });
      });
    }
    // Sample numbers; the words are the app's
    var SAMPLE = {
      downloading: function () { return '41% · 9.04MiB/s · ' + f('card.status.eta', '00:33'); },
      recording: function () { return g('card.status.recording') + ' · 00:06:03 · 117504KiB'; },
      paused: function () { return g('card.status.paused') + ' · 00:12:40 · 248320KiB'; },
      bulk: function () { return f('bulk.progress.mixed', 0, 2, 2); }
    };
    function applySamples() {
      $$('[data-tp-text]', win).forEach(function (el) { var fn = SAMPLE[el.getAttribute('data-tp-text')]; if (fn) el.textContent = fn(); });
    }

    // ── Theme ──
    var cur = sget(PKEY);
    if (!cur || !TH[cur]) cur = 'void';
    var recent = [];
    try { recent = JSON.parse(sget(RKEY) || '[]').filter(function (k) { return TH[k]; }); } catch (e) { recent = []; }
    function setTheme(key, remember) {
      frames.forEach(function (fr) { fr.classList.remove('t-' + cur); fr.classList.add('t-' + key); });
      cur = key;
      if (remember) {
        sset(PKEY, key);
        recent = [key].concat(recent.filter(function (k) { return k !== key; })).slice(0, 9);
        sset(RKEY, JSON.stringify(recent));
      }
      renderPicker();
      renderGrid();
    }

    // ── Themes menu (js/_theme.html renderPicker: current first, then recents, padded to 10 from the app's list) ──
    var panel = $('#hamburger-panel', win);
    var themesBtn = $('.nav-btn[data-nav="themes"]', win);
    function sw(c) { var d = document.createElement('div'); d.className = 'theme-sw'; d.style.background = c; return d; }
    function seasonalMark() { var m = document.createElement('span'); m.style.fontSize = '.55rem'; m.style.opacity = '.5'; m.textContent = '✦'; return m; }
    function renderPicker() {
      var list = $('#theme-list', win);
      if (!list) return;
      var base = [cur].concat(recent.filter(function (k) { return k !== cur; }));
      var show = base.length >= 10 ? base.slice(0, 10) : base.concat(D.order.filter(function (k) { return base.indexOf(k) < 0; })).slice(0, 10);
      list.textContent = '';
      show.forEach(function (key) {
        var d = TH[key];
        if (!d) return;
        var row = document.createElement('div');
        row.className = 'theme-row' + (key === cur ? ' active' : '');
        row.setAttribute('data-theme', key);
        row.setAttribute('role', 'button');
        row.tabIndex = 0;
        var swc = document.createElement('div'); swc.className = 'theme-swatches';
        swc.appendChild(sw(d.bg)); swc.appendChild(sw(d.surf)); swc.appendChild(sw(d.acc));
        var nm = document.createElement('span'); nm.className = 'theme-name'; nm.dir = 'auto'; nm.textContent = d.label;
        if (d.cat === 'seasonal') { nm.appendChild(document.createTextNode(' ')); nm.appendChild(seasonalMark()); }
        var ck = document.createElement('div'); ck.className = 'theme-check' + (key === cur ? ' checked' : '');
        row.appendChild(swc); row.appendChild(nm); row.appendChild(ck);
        var pick = function () { setTheme(key, true); closePanel(); };
        row.addEventListener('click', pick);
        row.addEventListener('keydown', function (e) { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); pick(); } });
        list.appendChild(row);
      });
    }
    function openPanel() {
      ['history', 'advanced'].forEach(function (t) { var el = $('#hpanel-' + t, win); if (el) el.style.display = 'none'; });
      var th = $('#hpanel-themes', win);
      if (th) th.style.display = '';
      panel.classList.add('open');
      themesBtn.classList.add('active');
    }
    function closePanel() { panel.classList.remove('open'); themesBtn.classList.remove('active'); }
    if (panel && themesBtn) {
      themesBtn.addEventListener('click', function (e) { e.stopPropagation(); if (panel.classList.contains('open')) closePanel(); else openPanel(); });
      document.addEventListener('click', function (e) { if (panel.classList.contains('open') && !inPath(e, panel) && !inPath(e, themesBtn)) closePanel(); });
      document.addEventListener('keydown', function (e) { if (e.key === 'Escape' && panel.classList.contains('open')) { closePanel(); themesBtn.focus(); } });
    }
    // Previews can't be exported and the page has nothing to import yet
    var imp = $('#theme-import-btn', win), exp = $('#theme-export-btn', win);
    if (imp) imp.style.display = 'none';
    if (exp) { exp.disabled = true; exp.style.opacity = '.45'; exp.style.cursor = 'not-allowed'; }
    var viewAll = $('.theme-btn-view-all', win);
    if (viewAll) viewAll.addEventListener('click', function () { closePanel(); openAll(); });

    // ── All Themes (themes.html: sidebar sections with counts, breadcrumb, sorted grid, search) ──
    var activeCat = 'all', searchQ = '';
    // Seasonal themes show only inside their window, by the visitor's own date (the app's seasonalVisibleKeys)
    var inSeason = D.seasonalVisibleKeys ? D.seasonalVisibleKeys(new Date()) : new Set();
    var KEYS = Object.keys(TH).filter(function (k) { return TH[k].cat !== 'seasonal' || inSeason.has(k); });
    function catLabel(id) { return g(id === 'seasonal' ? 'themes.filter.seasonal' : 'themes.cat.' + id) || D.catLabels[id] || id; }
    function countCat(cat) { return KEYS.filter(function (k) { return TH[k].cat === cat; }).length; }
    function getCollapsed() { try { return JSON.parse(sget(CKEY) || '[]'); } catch (e) { return []; } }
    function tab(cat, label, count, extra) {
      var d = document.createElement('div');
      d.className = 'cat-tab' + (extra || '') + (activeCat === cat ? ' active' : '');
      d.setAttribute('data-cat', cat);
      d.setAttribute('role', 'button');
      d.tabIndex = 0;
      if (cat === 'seasonal') { var m = document.createElement('span'); m.style.marginInlineEnd = '4px'; m.style.fontSize = '11px'; m.textContent = '✦'; d.appendChild(m); }
      d.appendChild(document.createTextNode(label));
      var c = document.createElement('span'); c.className = 'cat-count'; c.textContent = count; d.appendChild(c);
      var go = function () { activeCat = cat; buildSidebar(); renderGrid(); updateBreadcrumb(); };
      d.addEventListener('click', go);
      d.addEventListener('keydown', function (e) { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); go(); } });
      return d;
    }
    function buildSidebar() {
      var sb = $('#sidebar', atw);
      if (!sb) return;
      var collapsed = getCollapsed();
      sb.textContent = '';
      var cats = document.createElement('div'); cats.className = 'sidebar-cats';
      cats.appendChild(tab('all', g('themes.filter.all') || 'All', KEYS.length, ' all-tab'));
      if (countCat('seasonal')) cats.appendChild(tab('seasonal', g('themes.tab.seasonal') || 'Seasonal', countCat('seasonal')));
      var div = document.createElement('div'); div.className = 'cat-divider'; cats.appendChild(div);
      D.sections.forEach(function (sec) {
        var list = sec.cats.filter(function (c) { return c !== 'custom'; });   // Imported: the app's own saved themes, none on the page
        var isC = collapsed.indexOf(sec.label) >= 0;
        var h = document.createElement('div');
        h.className = 'cat-section' + (isC ? ' collapsed' : '');
        h.setAttribute('data-section', sec.label);
        h.setAttribute('role', 'button');
        h.tabIndex = 0;
        h.setAttribute('aria-expanded', isC ? 'false' : 'true');
        var lb = document.createElement('span'); lb.textContent = g(sec.key) || sec.label;
        var ca = document.createElement('span'); ca.className = 'section-caret'; ca.textContent = '▾';
        h.appendChild(lb); h.appendChild(ca);
        var grp = document.createElement('div'); grp.className = 'cat-group' + (isC ? ' collapsed' : '');
        grp.setAttribute('data-group', sec.label);
        list.forEach(function (c) { grp.appendChild(tab(c, catLabel(c), countCat(c))); });
        var toggle = function () {
          var cur2 = getCollapsed(), i = cur2.indexOf(sec.label);
          if (i >= 0) cur2.splice(i, 1); else cur2.push(sec.label);
          sset(CKEY, JSON.stringify(cur2));
          var now = cur2.indexOf(sec.label) >= 0;
          h.classList.toggle('collapsed', now); grp.classList.toggle('collapsed', now);
          h.setAttribute('aria-expanded', now ? 'false' : 'true');
        };
        h.addEventListener('click', toggle);
        h.addEventListener('keydown', function (e) { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); toggle(); } });
        cats.appendChild(h); cats.appendChild(grp);
      });
      sb.appendChild(cats);
    }
    function matches(k) {
      var d = TH[k];
      if (activeCat !== 'all' && d.cat !== activeCat) return false;
      if (searchQ && d.label.toLowerCase().indexOf(searchQ) < 0 && k.indexOf(searchQ) < 0) return false;
      return true;
    }
    function renderGrid() {
      var grid = $('#grid', atw);
      if (!grid) return;
      var keys = KEYS.filter(matches).sort(function (a, b) { return TH[a].label.localeCompare(TH[b].label); });
      grid.textContent = '';
      if (!keys.length) {
        var e = document.createElement('div'); e.className = 'empty'; e.textContent = g('themes.no_results'); grid.appendChild(e);
        return;
      }
      keys.forEach(function (key) {
        var d = TH[key];
        var c = document.createElement('div');
        c.className = 'theme-card' + (key === cur ? ' active' : '');
        c.setAttribute('data-theme', key);
        c.setAttribute('role', 'button');
        c.tabIndex = 0;
        var s = document.createElement('div'); s.className = 'swatches';
        [d.bg, d.surf, d.acc].forEach(function (col) { var x = document.createElement('div'); x.className = 'swatch'; x.style.background = col; s.appendChild(x); });
        var n = document.createElement('span'); n.className = 'card-name'; n.textContent = d.label;
        if (d.cat === 'seasonal') { var b = document.createElement('span'); b.className = 'seasonal-badge'; b.textContent = '✦'; n.appendChild(b); }
        c.appendChild(s); c.appendChild(n);
        var pick = function () { setTheme(key, true); };
        c.addEventListener('click', pick);
        c.addEventListener('keydown', function (ev) { if (ev.key === 'Enter' || ev.key === ' ') { ev.preventDefault(); pick(); } });
        grid.appendChild(c);
      });
    }
    function updateBreadcrumb() {
      var bar = $('#breadcrumb-bar', atw), bc = $('#bc-current', atw), cnt = $('#bc-count', atw);
      if (!bar) return;
      if (activeCat === 'all' && !searchQ) { bar.style.display = 'none'; return; }
      bar.style.display = 'flex';
      var n;
      if (searchQ) {
        n = KEYS.filter(function (k) { return TH[k].label.toLowerCase().indexOf(searchQ) >= 0 || k.indexOf(searchQ) >= 0; }).length;   // themes the grid shows
        bc.textContent = '"' + searchQ + '"';
        cnt.textContent = n === 1 ? f('themes.search.results_one', n) : f('themes.search.results_many', n);
      } else {
        n = countCat(activeCat);
        bc.textContent = catLabel(activeCat);
        cnt.textContent = n === 1 ? f('themes.breadcrumb.count_one', n) : f('themes.breadcrumb.count_many', n);
      }
    }
    var search = $('#search', atw);
    if (search) search.addEventListener('input', function () { searchQ = search.value.toLowerCase(); renderGrid(); updateBreadcrumb(); });
    var bcAll = $('#bc-all', atw);
    if (bcAll) bcAll.addEventListener('click', function () {
      activeCat = 'all'; searchQ = ''; if (search) search.value = '';
      buildSidebar(); renderGrid(); updateBreadcrumb();
    });
    function openAll() { atwHost.hidden = false; if (search) search.focus({ preventScroll: true }); }
    function closeAll() { atwHost.hidden = true; if (themesBtn) themesBtn.focus({ preventScroll: true }); }
    var closeBtn = $('#tp-atw-close', atw);
    if (closeBtn) closeBtn.addEventListener('click', closeAll);
    atw.addEventListener('keydown', function (e) { if (e.key === 'Escape' && !atwHost.hidden) closeAll(); });

    // ── Language: the app's footer selector and the site selector share one choice ──
    var sel = $('#lang-select', win);
    // The site's language menu (shared header). This page has no translated copies yet, so a pick switches the
    // preview here; the shared script saves the choice, as on the other pages.
    var menu = $('#langSel');
    function markSiteMenu() {
      if (!menu) return;
      $$('a[data-lang]', menu).forEach(function (a) {
        if (a.getAttribute('data-lang') === lang) a.setAttribute('aria-current', 'true'); else a.removeAttribute('aria-current');
      });
      var curEl = $('.lang-cur', menu);
      if (curEl) curEl.textContent = lang.toUpperCase();
    }
    if (menu) $$('a[data-lang]', menu).forEach(function (a) {
      a.addEventListener('click', function (e) {
        var c = a.getAttribute('data-lang');
        if (CODES.indexOf(c) < 0) return;
        e.preventDefault();
        setLang(c, true);
        menu.open = false;
      });
    });
    function buildFooterSelect() {   // js/_settings.html buildLangSelector: the active language first
      if (!sel) return;
      sel.textContent = '';
      [lang].concat(CODES.filter(function (c) { return c !== lang; })).forEach(function (c) {
        var o = document.createElement('option'); o.value = c; o.textContent = D.langs.names[c] || c; sel.appendChild(o);
      });
      sel.value = lang;
    }
    function setLang(code, remember) {
      if (CODES.indexOf(code) < 0) code = 'en';
      lang = code;
      STR = D.strings[code] || D.strings.en;
      var dir = D.langs.rtl.indexOf(code) >= 0 ? 'rtl' : 'ltr';
      frames.forEach(function (fr) { fr.setAttribute('lang', code); fr.setAttribute('dir', dir); applyStrings(fr); });
      applySamples();
      buildFooterSelect();
      markSiteMenu();
      buildSidebar();
      renderGrid();
      updateBreadcrumb();
      if (remember) sset(D.site.langKey, code);
    }
    if (sel) sel.addEventListener('change', function () { setLang(sel.value, true); });

    setLang(wantedLang(), false);
    frames.forEach(function (fr) { fr.classList.add('t-' + cur); });
    renderPicker();
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init); else init();
})();
